describe('migration from 0.0.2', () => {
  it.each(Object.keys(SCENARIOS))('%s: each branch shows what 0.0.2 showed, main first, old data untouched', async (name) => {
    const { legacy, expected } = frozen(name);
    let board = await migrate(legacy);
    expect(board.activeBranch()).toBe(expected.current);
    const listed = (await board.run({ method: 'branch.list' })) as { id: string; name: string }[];
    expect(listed[0].name).toBe('main');
    expect(listed.map((branch) => branch.id).sort()).toEqual(Object.keys(expected.branches).sort());
    for (const [id, { cards }] of Object.entries(expected.branches)) {
      await switchTo(board, id);
      expect(viewOf(board)).toEqual(trimmed(cards));
    }
    expect(await board.invariants()).toEqual([]);

    // A second open does not migrate again, even after the board changed.
    const branches = board.branches();
    await board.run({ method: 'card.create', params: { title: 'After migration' } });
    board = await board.reload();
    expect(board.branches()).toEqual(branches);
    expect(viewOf(board).map(([, title]) => title)).toContain('After migration');
    await board.close();
  });

  it('only the current branch, with live edits not in its snapshot, starts dirty', async () => {
    await migrate(frozen('live-edits').legacy).then((board) => board.close());
    const storage = indexedDbStorage();
    await storage.open();
    const [{ id }] = await storage.listBoards();
    const { branches } = (await storage.readBoard(id))!;
    const dirty = await Promise.all(branches.map(async (branch) => [branch.name, (await storage.readWorkingCopy(id, branch.id))!.copy.dirty]));
    expect(Object.fromEntries(dirty)).toEqual({ main: true, idea: false });
    await storage.close();
  });

  it('a branch of a branch keeps its parent, in the branch record and the commit', async () => {
    const board = await migrate(frozen('branch-of-branch').legacy);
    const listed = (await board.run({ method: 'branch.list' })) as { id: string; name: string; createdFrom: string | null }[];
    const named = (name: string) => listed.find((branch) => branch.name === name)!;
    expect(listed.map((branch) => [branch.name, branch.createdFrom && listed.find((other) => other.id === branch.createdFrom)!.name])).toEqual([
      ['main', null], ['feature', 'main'], ['feature-ui', 'feature'],
    ]);
    await board.close();
    // Each migrated commit's parent is the commit of the branch it was created from.
    const storage = indexedDbStorage();
    await storage.open();
    const boardId = (await storage.listBoards())[0].id;
    const baseOf = async (name: string) => (await storage.readWorkingCopy(boardId, named(name).id))!.copy.baseCommitId;
    const [main, feature, ui] = await storage.readCommits(boardId, [await baseOf('main'), await baseOf('feature'), await baseOf('feature-ui')]);
    expect([main.parents, feature.parents, ui.parents]).toEqual([[], [main.id], [feature.id]]);
    await storage.close();
  });

  it('renames repeated names ignoring case, in creation order, and lists every rename', async () => {
    const { legacy, expected } = frozen('repeated-names');
    const board = await migrate(legacy);
    const listed = (await board.run({ method: 'branch.list' })) as { id: string; name: string }[];
    expect(listed.map((branch) => branch.name)).toEqual(['main', 'idea', 'idea-2', 'idea-3']);
    expect(listed.map((branch) => expected.branches[branch.id].name)).toEqual(['main', 'idea', 'idea', 'Idea']);
    expect((await marker())!.notes!.filter((note) => note.what.startsWith('renamed'))).toEqual([
      { branchId: listed[2].id, what: 'renamed from "idea" to "idea-2"' },
      { branchId: listed[3].id, what: 'renamed from "Idea" to "idea-3"' },
    ]);
    await board.close();
  });

  it('keeps over-limit values, trims all but descriptions, drops repeated tags and "Unassigned"', async () => {
    const board = await migrate(frozen('over-limit').legacy);
    const { cards } = (await board.run({ method: 'board.view' })) as { cards: Record<string, unknown>[] };
    const long = cards.find((card) => String(card.title).startsWith('Long'))!;
    expect(long.title).toBe('Long title '.repeat(45).trim());
    expect(long.description).toBe('  Keep **these** spaces  \n');
    expect(long.assignee).toBe('Ann');
    expect(long.tags).toEqual([...Array.from({ length: 22 }, (_, i) => `tag-${i}`), 'x'.repeat(60), 'spaced']);
    expect(cards.find((card) => card.title === 'Nobody')).not.toHaveProperty('assignee');
    const notes = (await marker())!.notes!.filter((note) => note.cardId === long.id).map((note) => note.what);
    expect(notes).toEqual(expect.arrayContaining(['title trimmed', 'tag trimmed', 'a repeated tag was dropped', 'assignee trimmed']));
    await board.close();
  });

  it('lists main first even when another branch is older, and says so', async () => {
    const { legacy } = frozen('older-than-main');
    const idea = JSON.parse(legacy.localStorage['kanban-branches']).branches.find(([, value]: [string, { name: string }]) => value.name === 'idea')[1];
    const board = await migrate(legacy);
    const listed = (await board.run({ method: 'branch.list' })) as { name: string; createdAt: number }[];
    expect(listed.map((branch) => branch.name)).toEqual(['main', 'idea']);
    expect(listed[0].createdAt).toBeLessThan(idea.createdAt);
    expect((await marker())!.notes).toContainEqual({ branchId: 'main', what: 'creation time moved before every other branch, so main is listed first' });
    await board.close();
  });

  it('skips snapshots of unlisted branches, and says so', async () => {
    const board = await migrate(frozen('phantom-snapshot').legacy);
    expect(board.branches()).toEqual(['main']);
    expect((await marker())!.notes).toContainEqual({ what: '2 snapshots of branches that are not listed were not migrated' });
    await board.close();
  });

  it('an unreadable branch list starts a fresh board, records why, and keeps the old data', async () => {
    const { legacy } = frozen('plain');
    const board = await migrate({ ...legacy, localStorage: { ...legacy.localStorage, 'kanban-branches': '{' } });
    expect(viewOf(board)).toEqual([]);
    expect(await marker()).toMatchObject({ from: 'kanban-light', failed: 'the 0.0.2 branch list cannot be read' });
    expect(localStorage.getItem('kanban-branches')).toBe('{');
    await board.close();
  });

  it('old data that cannot be read right now writes nothing, so the next open migrates', async () => {
    const { legacy, expected } = frozen('plain');
    const broken: LegacySource = { read: () => Promise.reject({ code: 'unavailable' }) };
    await expect(migrate(legacy, broken)).rejects.toMatchObject({ code: 'storage-unavailable' });
    const storage = indexedDbStorage();
    expect(await storage.open()).toEqual({ status: 'empty' });
    await storage.close();
    const board = await openServiceBoard(() => indexedDbStorage(), legacyWebSource());
    expect(viewOf(board)).toEqual(trimmed(expected.branches.main.cards));
    await board.close();
  });

  it('two tabs opening together migrate once', async () => {
    const { legacy, expected } = frozen('branch-of-branch');
    await seedLegacy(legacy);
    const h = harness(() => () => indexedDbStorage());
    const tabs = await Promise.all([h.open({ legacy: legacyWebSource() }), h.open({ legacy: legacyWebSource() })]);
    expect(tabs.map((tab) => tab.readOnly()).sort()).toEqual([false, true]);
    const raw = indexedDbStorage();
    await raw.open();
    const [{ id }] = await raw.listBoards();
    // One migration commit per branch: a second migration would have added as many again.
    expect(await raw.listCommitIds(id)).toHaveLength(Object.keys(expected.branches).length);
    await raw.close();
    await Promise.all(tabs.map((tab) => tab.close()));
  });

  it('a migrated batch that fails to store writes nothing, so the next open migrates', async () => {
    const { legacy, expected } = frozen('plain');
    await seedLegacy(legacy);
    const h = harness(() => () => indexedDbStorage());
    const failing = faulty(indexedDbStorage(), { failApply: 1 });
    expect(await rejection(h.open({ storage: failing, legacy: legacyWebSource() }))).toMatchObject({ code: 'storage-failed' });
    expect(await marker()).toBeNull();
    const board = await h.open({ legacy: legacyWebSource() });
    expect(titles(board.state()!.current.cards)).toEqual(expected.branches.main.cards.map(([, title]) => title).sort());
    await board.close();
  });

  it('with no old data, nothing is migrated and no kanban-light database is created', async () => {
    const board = await openServiceBoard(() => indexedDbStorage(), legacyWebSource());
    expect(viewOf(board)).toEqual([]);
    expect(await marker()).toBeNull();
    expect((await indexedDB.databases()).map((db) => db.name)).toEqual(['kanbanlight']);
    await board.close();
  });
});

describe('repairs (Q15)', () => {
  const env = () => ({ clock: counterClock({ value: 5000 }), ids: counterIds({ value: 0 }) });
  const list = (cards: unknown[]) => ({
    indexedDB: { cards },
    localStorage: { 'kanban-branches': JSON.stringify({ branches: [['main', { id: 'main', name: 'main', createdAt: 1 }]], currentBranch: 'main' }) },
  });

  it('repairs corrupt cards and skips only non-objects, listing each', async () => {
    const result = convertLegacy(env(), list([
      { id: 'a', title: { nested: true }, priority: 'urgent', columnId: 'later', tags: 'x', position: 'top' },
      { title: 7, description: null, assignee: 3, createdAt: 'now' },
      { id: 'a', title: ' twin ' },
      'not a card',
      null,
    ]));
    if (!result.ok) throw new Error(result.reason);
    const cards = result.value.batch.flatMap((change) => (change.kind === 'putCard' ? [change.card] : []));
    expect(cards.map(({ id, title, priority, columnId, tags }) => ({ id, title, priority, columnId, tags }))).toEqual([
      { id: 'a', title: '{"nested":true}', priority: 'medium', columnId: 'backlog', tags: [] },
      { id: 'card-2', title: '7', priority: 'medium', columnId: 'backlog', tags: [] },
      { id: 'card-3', title: 'twin', priority: 'medium', columnId: 'backlog', tags: [] },
    ]);
    const notes = result.value.notes.map(({ cardId, what }) => `${cardId ?? '-'}: ${what}`);
    expect(notes).toEqual(expect.arrayContaining([
      'a: title was not text; converted',
      'a: unknown priority; set to medium',
      'a: unknown column; moved to backlog',
      'a: tags were not a list; emptied',
      'a: position was not a number; set from the list order',
      'card-2: had no usable id; given a new id',
      'card-2: description was not text; emptied',
      'card-2: empty, "Unassigned" or non-text assignee dropped',
      'card-3: repeated another card id; given a new id',
      '-: entry 3 is not a card and was skipped',
      '-: entry 4 is not a card and was skipped',
    ]));
    const storage = checked(memoryStorage(createMemoryBacking()));
    await storage.open();
    await storage.apply(result.value.batch);
  });

  it('an unlisted current branch is listed as recovered, and a missing main is recreated first', () => {
    const idea = { id: 'b-1', name: 'recovered', createdAt: 1 };
    const data = { indexedDB: {}, localStorage: { 'kanban-branches': JSON.stringify({ branches: [['b-1', idea]], currentBranch: 'b-9' }) } };
    const result = convertLegacy(env(), data);
    if (!result.ok) throw new Error(result.reason);
    const branches = result.value.batch.flatMap((change) => (change.kind === 'putBranch' ? [change.branch] : []));
    expect(branches.map(({ id, name }) => [id, name])).toEqual([['main', 'main'], ['b-1', 'recovered'], ['b-9', 'recovered-2']]);
    expect(result.value.batch).toContainEqual({ kind: 'setHead', head: { boardId: 'default-board', branchId: 'b-9' } });
    expect(result.value.notes).toEqual(expect.arrayContaining([
      { branchId: 'b-9', what: 'the current branch was not listed; listed as recovered' },
      { branchId: 'main', what: 'main was not listed; recreated' },
    ]));
  });

  it('whatever the cards hold, conversion never throws and its batch always stores', async () => {
    const junk = fc.oneof(fc.anything(), fc.record({
      id: fc.anything(), title: fc.anything(), description: fc.anything(), priority: fc.anything(), assignee: fc.anything(),
      tags: fc.oneof(fc.anything(), fc.array(fc.anything())), columnId: fc.anything(), position: fc.anything(),
      createdAt: fc.anything(), updatedAt: fc.anything(), boardId: fc.anything(), extra: fc.anything(),
    }, { requiredKeys: [] }));
    await fc.assert(
      fc.asyncProperty(fc.array(junk, { maxLength: 8 }), fc.array(junk, { maxLength: 8 }), async (live, snapshot) => {
        const data = list(live);
        (data.indexedDB as Record<string, unknown[]>).snapshots = [{ id: 's', branchId: 'main', timestamp: 2, data: { cards: snapshot } }];
        const result = convertLegacy(env(), JSON.parse(JSON.stringify(data)));
        expect(result.ok).toBe(true);
        const storage = checked(memoryStorage(createMemoryBacking()));
        await storage.open();
        if (result.ok) await storage.apply(result.value.batch);
      }),
      { numRuns: 200, seed: 1 }
    );
  });
});

describe('a large 0.0.2 board', () => {
  it('migrates within the recorded time', async () => {
    const fixture = await generate(async (step, open) => {
      const board = await open();
      const { useKanbanStore } = await import('../src/store/useKanbanStore');
      for (const name of ['big-1', 'big-2']) {
        for (let i = 0; i < 300; i++) {
          step();
          await useKanbanStore.getState().createCard(`Card ${name} ${i}`, 'todo', { description: 'd'.repeat(200), tags: ['a', 'b'] });
        }
        step();
        await board.branch(name);
      }
      return { board, current: 'main' };
    });
    const size = JSON.stringify(fixture.legacy).length;
    const started = performance.now();
    const board = await migrate(fixture.legacy);
    const took = performance.now() - started;
    const list = fixture.legacy.localStorage['kanban-branches'].length;
    console.info(`large board: ${(size / 1e6).toFixed(1)} MB of 0.0.2 data (kanban-branches ${(list / 1e6).toFixed(2)} MB) migrated in ${Math.round(took)} ms`);
    for (const [id, { cards }] of Object.entries(fixture.expected.branches)) {
      await switchTo(board, id);
      expect(viewOf(board)).toEqual(trimmed(cards));
    }
    expect(took).toBeLessThan(10_000);
    await board.close();
  }, 120_000);
});

// A real board, only from the git-ignored test/fixtures/private/ (a recovery download). Checks
// counts and structure only; nothing from the board is printed.
const PRIVATE = 'test/fixtures/private';
const privateFiles = fs.existsSync(PRIVATE) ? fs.readdirSync(PRIVATE).filter((file) => file.endsWith('.json')) : [];

describe.skipIf(privateFiles.length === 0)('a private 0.0.2 board', () => {
  it.each(privateFiles)('%s migrates without failing, keeps every live card, and leaves the old data untouched', async (file) => {
    const legacy = JSON.parse(fs.readFileSync(`${PRIVATE}/${file}`, 'utf8')) as LegacyData;
    const board = await migrate(legacy, legacyWebSource(), { quiet: true });
    expect((await marker())?.failed === undefined).toBe(true);
    expect(await board.invariants()).toEqual([]);
    const listed = JSON.parse(legacy.localStorage['kanban-branches'] ?? '{"branches":[]}').branches.map(([id]: [string]) => id);
    expect(listed.every((id: string) => board.branches().includes(id))).toBe(true);
    const live = (legacy.indexedDB.cards ?? []).filter((card) => typeof card === 'object' && card !== null).length;
    expect(viewOf(board).length).toBe(live);
    await board.close();
  }, 120_000);
});

const FROZEN = import.meta.glob<LegacyFixture>('./fixtures/v0.0.2/*.json', { eager: true, import: 'default' });
const frozen = (name: string): LegacyFixture => structuredClone(FROZEN[`./fixtures/v0.0.2/${name}.json`]);

// Node's fs, for the two things a module import cannot do: write the frozen copies, and list the
// private folder at run time (an import.meta.glob result is cached with the test module).
// Paths are relative to the repository root, where npm test runs.
type Fs = {
  existsSync(path: string): boolean;
  readdirSync(path: string): string[];
  readFileSync(path: string, encoding: 'utf8'): string;
  writeFileSync(path: string, text: string): void;
};
const fs: Fs = await import('node:fs' as string);

// UPDATE_FIXTURES=1 npm test rewrites the frozen copies from the 0.0.2 code.
function writeFrozen(name: string, fixture: LegacyFixture) {
  fs.writeFileSync(`test/fixtures/v0.0.2/${name}.json`, `${JSON.stringify(fixture, null, 1)}\n`);
}

async function migrate(legacy: LegacyData, source: LegacySource = legacyWebSource(), { quiet = false } = {}) {
  await seedLegacy(legacy);
  const before = await dumpLegacy();
  const board = await openServiceBoard(() => indexedDbStorage(), source);
  // Quiet: a failure says only that the old data changed, never what it holds.
  if (quiet) expect(JSON.stringify(await dumpLegacy()) === JSON.stringify(before)).toBe(true);
  else expect(await dumpLegacy()).toEqual(before);
  return board;
}

async function marker() {
  const storage = indexedDbStorage();
  await storage.open();
  const value = (await storage.readMeta(MIGRATION_KEY)) as { notes?: MigrationNote[]; failed?: string } | null;
  await storage.close();
  return value;
}

const trimmed = (cards: CardView[]) => cards.map(([id, title, column]) => [id, title.trim(), column]);
const viewOf = (board: ServiceBoardDriver) => JSON.parse(board.view()) as CardView[];

async function switchTo(board: ServiceBoardDriver, id: string) {
  await board.run({ method: 'branch.switch', params: { branch: id } });
}

